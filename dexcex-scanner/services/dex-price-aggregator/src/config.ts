/** Build list of chain:address for DeFiLlama API */
export function getDefiLlamaCoinIds(): string[] {
  const ids: string[] = [];
  for (const chain of CHAINS) {
    const addrs = TOKENS_BY_CHAIN[chain];
    if (!addrs) continue;
    for (const addr of addrs) {
      ids.push(`${chain}:${addr}`);
    }
  }
  return ids;
}
